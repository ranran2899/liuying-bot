"""QQ表情编号映射

QQ经典表情编号到中文名的映射表，用于将消息中的QQ表情ID
解析为可读名称，便于LLM理解与日志展示。
"""


class QQFaceNames:
    """QQ表情名称映射

    提供按编号查询表情中文名的能力。
    """

    def __init__(self) -> None:
        """初始化QQ表情映射"""
        self._faces: dict[int, str] = dict(_QQ_FACES)
        """表情ID -> 中文名"""

    def get_name(self, face_id: int) -> str:
        """获取表情中文名

        参数:
            face_id: QQ表情编号

        返回:
            str: 中文名，未知返回"未知表情"
        """
        return self._faces.get(face_id, "未知表情")

    def has(self, face_id: int) -> bool:
        """判断表情编号是否存在

        参数:
            face_id: QQ表情编号

        返回:
            bool: 是否存在映射
        """
        return face_id in self._faces

    def add(self, face_id: int, name: str) -> None:
        """新增或覆盖表情映射

        参数:
            face_id: QQ表情编号
            name: 中文名
        """
        self._faces[face_id] = name

    def all(self) -> dict[int, str]:
        """获取全部表情映射

        返回:
            dict: 表情ID -> 中文名的副本
        """
        return dict(self._faces)


