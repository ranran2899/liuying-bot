_STICKER_MEME_LINE = (
    "- 表情包、梗图和截图只当作语气线索；"
    "除非对方明确让你识别、翻译或解读，"
    "不要主动讲图里是什么。"
)
"""表情包梗图约束行"""

_VISUAL_GUARD_PROMPT = """

## 图片处理规则（重要）
1. 你正在接收图片输入，但仍然保持自己的人设和当前聊天关系。
2. 禁止代入、扮演图片中的人物或角色。
3. 图片内容只用于理解当前语境；没有被明确要求时，不要主动讲解、复述或分析画面。
4. 如果需要回应，像聊天对象看见这条消息后的自然反应，不要写成图像识别报告。"""
"""图片身份保护提示词"""

